#!/usr/bin/env python3
"""Regenerate a task's CoT reasoning with a base model plus an Align LoRA."""

from __future__ import annotations

import argparse
import hashlib
import json
import os
import re
import shutil
import sys
import time
from copy import deepcopy
from pathlib import Path
from typing import Any, Iterable


SCRIPT_PATH = Path(__file__).resolve()
PROJECT_ROOT = SCRIPT_PATH.parents[2]
TRAINING_DIR = PROJECT_ROOT / "training"
if str(TRAINING_DIR) not in sys.path:
    sys.path.insert(0, str(TRAINING_DIR))

DEFAULT_SOURCE_ROOT = PROJECT_ROOT / "data"
DEFAULT_OUTPUT_ROOT = SCRIPT_PATH.parent
REASONING_RE = re.compile(r"<reasoning>\s*(.*?)\s*</reasoning>", re.I | re.S)
SCORE_RE = re.compile(r"<score>\s*(-?\d+)\s*</score>", re.I)
TAG_RE = re.compile(r"</?(?:reasoning|score)>|<score>\s*-?\d+\s*</score>", re.I)


